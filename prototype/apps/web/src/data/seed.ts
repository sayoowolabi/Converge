/** Daily availability windows 12:00–23:30, Tuesday to Sunday, 19 Nov 2026 – 31 Jan 2027. */
function availability(): TimeRange[] {
  const windows: TimeRange[] = [];
  const day = new Date(Date.UTC(2026, 10, 19));
  const end = new Date(Date.UTC(2027, 0, 31));
  while (day <= end) {
    if (day.getUTCDay() !== 1) {
      const date = day.toISOString().slice(0, 10);
      windows.push({ startsAt: dublinToIso(date, "12:00"), endsAt: dublinToIso(date, "23:30") });
    }
    day.setUTCDate(day.getUTCDate() + 1);
  }
  return windows;
}

